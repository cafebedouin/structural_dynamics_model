#!/usr/bin/env python3
"""OQ-207 census: stakeholder-frame H1 across the three live legs + kernel_v1.

Two-stage per design D8 (the census reads an INTERMEDIATE ARTIFACT, which pins
the planted-violation injection point at the read site, not post-read):

  Stage 1 — serialized one-shot swipl goals per corpus (never concurrent),
  each: corpus_path overlay (retractall+assertz, the witnessed recipe) ->
  cache_registry:clear_all_caches (D7) -> load_all_testsets -> dump
  census_input_<leg>.json of per-constraint records
  {id, h0, h1, n_seats, n_real, verdict, plural_has_unknown, n_excluded}.
  The verdict class rides in the artifact because (h1, n_seats, n_real) alone
  cannot distinguish the seats_untyped stratum from cell (b) (both n_real=0
  with seats present).

  Stage 2 — the assertion layer consumes ONLY those artifacts and computes:
  null-cause strata, H1 distribution keyed by n_real, spectrum violations
  (must be 0), mcc-coherence cell counts (D4 table incl. divergence cells (a),
  (b) and the mixed plural([T,unknown]) cell) — every rate with raw count +
  n_in_domain (OQ-136).

Controls:
  - kernel_v1 all-null: zero stakeholder facts -> every record must read
    (null, null, 0, 0, no_agent_seats) — the negative-domain control.
  - planted violation: a doctored COPY of a census_input artifact (an
    out-of-spectrum h1 at a valid n_real) run through the SAME assertion path
    and shown FLAGGED — proving the probe fires on the artifact it audits.
  - zero-seat counts vs the OQ-202 mint strata 26/466/212 (drift = finding,
    not failure; reported, never asserted).

KILL CONDITION (D4) — FIRED 2026-07-12 (cell (b) live = 4) and RESOLVED by the
OQ-217 tightening (commit 871e69ac): consensus verdicts now compute over
is_real_type/1 seats only, so the divergence cells (a)/(b)/mixed are RETIRED.
Post-OQ-217 this script asserts their populations are ZERO — the detectors
stay live as regression tripwires (deleting them would be Build Discipline
Pattern 5: a gate satisfied by absence of its input). New coherent cells:
insufficient_real_seats, coherent_unanimous_untypeable.

Spectrum machinery is IMPORTED from oq195_h1_spectrum_check (Lemma-1 brute
force + T-bound), never forked; T is derived from code exactly as that script
derives it.

Usage: python3 python/audits/oq207_stakeholder_h1_census.py [--outdir DIR]
       [--skip-dump]   (reuse existing census_input_*.json artifacts)
Exit nonzero on: spectrum violation, incoherent mcc cell, null-rule violation,
kernel_v1 control failure, or a planted control that does NOT fire.
"""
