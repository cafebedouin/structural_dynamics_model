#!/usr/bin/env python3
"""Generate the five OQ-93 grid-viability probe stories (.pl) from the
pre-registered value table. Run from the audit dir. The table here IS the
preregistration's input spec — change it only by amending PREREGISTRATION.md."""
from pathlib import Path

OUT = Path(__file__).resolve().parent / "stories"
OUT.mkdir(exist_ok=True)

LEVELS = ["structural", "organizational", "class", "individual"]
METRICS = ["accessibility_collapse", "stakes_inflation", "suppression", "resistance"]
T0, TN = 0, 10

# story -> {level: (V_T0, V_Tn)}
STORIES = {
    "grid_probe_rising":        {l: (0.20, 0.80) for l in LEVELS},
    "grid_probe_falling":       {l: (0.80, 0.20) for l in LEVELS},
    "grid_probe_flat_authored": {l: (0.50, 0.50) for l in LEVELS},
    "grid_probe_divergent":     {"structural": (0.20, 0.80), "organizational": (0.50, 0.50),
                                 "class": (0.50, 0.50), "individual": (0.80, 0.20)},
    "grid_probe_intent_max":    {l: (0.00, 1.00) for l in LEVELS},
}

HEADER = """% ============================================================================
% OQ-93 GRID-VIABILITY PROBE STORY: {cid}
% Generated by make_probe_stories.py from the pre-registered value table.
% NOT a corpus testset — lives in the audit dir, run via load_and_run by path.
% All 32 grid points AUTHORED (source ids probe_auth_*); shim must be OFF.
% ============================================================================

:- module(constraint_{cid}, []).

:- use_module(constraint_indexing).
:- use_module(domain_priors).
:- use_module(narrative_ontology).

:- multifile
    domain_priors:base_extractiveness/2,
    domain_priors:suppression_score/2,
    domain_priors:theater_ratio/2,
    narrative_ontology:interval/3,
    narrative_ontology:measurement/5,
    narrative_ontology:constraint_metric/3,
    narrative_ontology:intent_viable_alternative/3,
    narrative_ontology:intent_alternative_rejected/3,
    narrative_ontology:intent_power_change/3,
    narrative_ontology:intent_suppression_level/4,
    narrative_ontology:intent_resistance_level/4.

narrative_ontology:interval({cid}, 0, 10).
domain_priors:base_extractiveness({cid}, 0.50).
domain_priors:suppression_score({cid}, 0.40).
domain_priors:theater_ratio({cid}, 0.20).
narrative_ontology:constraint_metric({cid}, extractiveness, 0.50).
narrative_ontology:constraint_metric({cid}, suppression_requirement, 0.40).
narrative_ontology:constraint_metric({cid}, theater_ratio, 0.20).

% --- AUTHORED 32-point grid ({cid}) ---
"""

INTENT_FACTS = """
% --- Best-case authored intent evidence (Conditions 2-4; the only producer
% these tables have ever had) ---
narrative_ontology:intent_viable_alternative({cid}, system_a, alt_x).
narrative_ontology:intent_alternative_rejected({cid}, system_a, alt_x).
narrative_ontology:intent_power_change({cid}, corporate_elite, 0.80).
narrative_ontology:intent_suppression_level({cid}, corporate_elite, structural, 0.90).
narrative_ontology:intent_resistance_level({cid}, corporate_elite, structural, 0.90).
"""

for cid, table in STORIES.items():
    lines = [HEADER.format(cid=cid)]
    n = 0
    for level in LEVELS:
        v0, vn = table[level]
        for metric in METRICS:
            for t, v in ((T0, v0), (TN, vn)):
                n += 1
                lines.append(
                    f"narrative_ontology:measurement(probe_auth_{n:02d}, {cid}, "
                    f"{metric}({level}), {t}, {v:.2f}).")
    assert n == 32
    if cid == "grid_probe_intent_max":
        lines.append(INTENT_FACTS.format(cid=cid))
    (OUT / f"{cid}.pl").write_text("\n".join(lines) + "\n")
    print(f"wrote stories/{cid}.pl (32 grid facts)")
